import { AlertTriangle } from "lucide-react";
import { Link } from "react-router-dom";
import { statusToneMap } from "../lib/format";

export default function AlertsPanel({
  alerts,
  title = "Recent Alerts",
  subtitle = "Escalations generated by threshold rules"
}) {
  return (
    <div id="alerts" className="glass-panel p-5 md:p-6">
      <div className="mb-4 flex items-center gap-3">
        <div className="icon-chip bg-critical/15 text-critical ring-critical/20">
          <AlertTriangle size={20} />
        </div>
        <div>
          <p className="eyebrow">Alert Feed</p>
          <p className="mt-1 text-xl font-semibold text-white">{title}</p>
          <p className="text-sm text-slate-400">{subtitle}</p>
        </div>
      </div>

      <div className="space-y-3">
        {alerts.length ? (
          alerts.map((alert) => (
            <div
              key={alert.id}
              className="rounded-2xl border border-white/10 bg-slate-950/30 p-4"
            >
              <div className="flex items-start justify-between gap-3">
                <div>
                  <Link to={`/patients/${alert.patientId}`} className="font-medium text-white hover:text-teal">
                    {alert.patientName}
                    {alert.room ? <span className="text-slate-500"> | {alert.room}</span> : null}
                  </Link>
                  <p className="mt-1 text-sm leading-6 text-slate-300">{alert.issue}</p>
                </div>
                <span
                  className={`rounded-full px-3 py-1 text-xs font-semibold ring-1 ${
                    alert.severity === "Critical" ? statusToneMap.critical : statusToneMap.warning
                  }`}
                >
                  {alert.severity}
                </span>
              </div>
              <p className="mt-3 text-xs uppercase tracking-[0.18em] text-slate-500">{alert.time}</p>
            </div>
          ))
        ) : (
          <div className="rounded-2xl border border-white/10 bg-slate-950/30 p-5 text-sm text-slate-400">
            No alerts yet. The stream will surface watch and high-risk events automatically.
          </div>
        )}
      </div>
    </div>
  );
}
